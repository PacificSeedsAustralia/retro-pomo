_cache = {}


def _key_color(c):
    return None if c is None else tuple(pygame.Color(c))


def _raw(text, color, spacing):
    glyphs = [_G.get(ch, _G["?"]) for ch in text]
    width = sum(len(g[0]) for g in glyphs) + spacing * max(0, len(glyphs) - 1)
    surf = pygame.Surface((max(1, width), 7), pygame.SRCALPHA)
    x = 0
    for g in glyphs:
        for y, row in enumerate(g):
            for dx, ch in enumerate(row):
                if ch == "#":
                    surf.set_at((x + dx, y), color)
        x += len(g[0]) + spacing
    return surf


def text_surface(text, scale=2, color=(255, 255, 255), shadow=None, spacing=1):
    text = str(text).upper()
    key = (text, scale, _key_color(color), _key_color(shadow), spacing)
    surf = _cache.get(key)
    if surf is not None:
        return surf
    raw = _raw(text, color, spacing)
    w, h = raw.get_width() * scale, 7 * scale
    main = pygame.transform.scale(raw, (w, h))
    if shadow is not None:
        off = max(1, scale // 2)
        out = pygame.Surface((w + off, h + off), pygame.SRCALPHA)
        out.blit(pygame.transform.scale(_raw(text, shadow, spacing), (w, h)), (off, off))
        out.blit(main, (0, 0))
        main = out
    if len(_cache) > 400:
        _cache.clear()
    _cache[key] = main
    return main


def draw_text(surf, text, pos, scale=2, color=(255, 255, 255), shadow=None, anchor="topleft"):
    s = text_surface(text, scale, color, shadow)
    r = s.get_rect(**{anchor: pos})
    surf.blit(s, r)
    return r
